'use client';

import React, { Suspense, useCallback, useEffect, useMemo, useState } from 'react';
import { useSearchParams } from 'next/navigation';
import { Check, Download, Film, Play, Save, XCircle } from 'lucide-react';
import { ConnectGate, useAuth } from '@/components/AuthProvider';
import { Notice } from '@/components/ui/Notice';
import { usePolled } from '@/hooks/usePolled';
import {
  approveVideo, cancelVideo, createVideo, getVideo, getVideoCapabilities, listReports, listVideos, renderVideo, saveStoryboard, videoMp4Url,
} from '@/lib/api';
import { slug, triggerDownload } from '@/lib/download';
import { formatBytes, formatDateTime } from '@/lib/format';
import type { Report, Scene, VideoCapabilities, VideoJob, VideoState } from '@/lib/types';

const SECTIONS: { id: string; label: string }[] = [
  { id: 'title', label: 'Title' },
  { id: 'kpis', label: 'KPIs' },
  { id: 'llm', label: 'LLM' },
  { id: 'rag', label: 'RAG' },
  { id: 'agent', label: 'Agent' },
  { id: 'failures', label: 'Failures' },
  { id: 'stats', label: 'Statistics' },
  { id: 'recommendations', label: 'Recommendations' },
  { id: 'closing', label: 'Closing' },
];
const TIMELINE: VideoState[] = ['QUEUED', 'GENERATING_SCRIPT', 'AWAITING_APPROVAL', 'RENDERING', 'COMPLETED', 'FAILED', 'CANCELLED'];
const ACTIVE: VideoState[] = ['QUEUED', 'GENERATING_SCRIPT', 'RENDERING'];
const label = (s: string) => s.replace(/_/g, ' ').toLowerCase().replace(/^./, (c) => c.toUpperCase());

interface Draft {
  id: string;
  title: string;
  on_screen_text: string;
  narration: string;
  duration_seconds: number;
}

function Video({ initialReport }: { initialReport: string }) {
  const { token } = useAuth();
  const [caps, setCaps] = useState<VideoCapabilities | null>(null);
  const [reports, setReports] = useState<Report[]>([]);
  const [jobs, setJobs] = useState<VideoJob[]>([]);
  const [error, setError] = useState<string | null>(null);

  const [reportId, setReportId] = useState(initialReport);
  const [duration, setDuration] = useState<60 | 120 | 180>(60);
  const [mode, setMode] = useState<'silent' | 'narrated'>('silent');
  const [voice, setVoice] = useState('');
  const [captions, setCaptions] = useState(true);
  const [sections, setSections] = useState<string[]>(SECTIONS.map((s) => s.id));
  const [creating, setCreating] = useState(false);

  const [selected, setSelected] = useState<string | null>(null);
  const [version, setVersion] = useState(0);

  const refreshJobs = useCallback(async () => {
    try {
      setJobs(await listVideos());
    } catch (e) {
      setError(e instanceof Error ? e.message : 'Failed to load video jobs');
    }
  }, []);

  useEffect(() => {
    if (!token) return;
    let live = true;
    Promise.all([getVideoCapabilities(), listReports(), listVideos()])
      .then(([c, r, j]) => {
        if (!live) return;
        setCaps(c);
        setReports(r.filter((x) => x.status === 'COMPLETED'));
        setJobs(j);
      })
      .catch((e: unknown) => live && setError(e instanceof Error ? e.message : 'Failed to load video studio data'));
    return () => {
      live = false;
    };
  }, [token]);

  const create = async (e: React.FormEvent) => {
    e.preventDefault();
    setCreating(true);
    setError(null);
    try {
      const job = await createVideo({ report_id: reportId, duration_seconds: duration, mode, voice: mode === 'narrated' && voice ? voice : undefined, captions, sections });
      setSelected(job.id);
      setVersion((v) => v + 1);
      await refreshJobs();
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Could not create the video job');
    } finally {
      setCreating(false);
    }
  };

  const loader = useCallback(() => getVideo(selected as string), [selected, version]); // eslint-disable-line react-hooks/exhaustive-deps
  const { data, setData, error: pollError } = usePolled<VideoJob>(selected ? loader : null, (j) => !ACTIVE.includes(j.state), 2000);
  const job = data && data.id === selected ? data : null;

  useEffect(() => {
    if (job) setJobs((cur) => cur.map((j) => (j.id === job.id ? job : j)));
  }, [job]);

  const ttsOk = caps?.tts_available ?? false;
  const maxDur = caps?.max_duration_seconds ?? 180;

  return (
    <div className="space-y-6">
      <header>
        <h1 className="text-2xl font-bold">Video Studio</h1>
        <p className="text-sm text-slate-600">Turn a completed report into a short explainer video. Review and approve the storyboard before rendering.</p>
      </header>
      {error && <Notice tone="error">{error}</Notice>}
      <Notice>
        The script is generated by Claude through Mubit when Mubit is configured{caps ? ` (currently ${caps.mubit_configured ? 'configured' : 'not configured'})` : ''}; otherwise a deterministic template built from the report data is used.
        Each job shows its storyboard source. Renderer: {caps?.renderer ?? '…'}.
      </Notice>

      <form onSubmit={create} className="card grid gap-4 md:grid-cols-2" aria-label="Create video job">
        <div className="md:col-span-2">
          <label className="label" htmlFor="v-report">Completed report</label>
          <select id="v-report" className="input" value={reportId} onChange={(e) => setReportId(e.target.value)} required>
            <option value="">Select a report…</option>
            {reportId && !reports.some((r) => r.id === reportId) && <option value={reportId}>{reportId}</option>}
            {reports.map((r) => <option key={r.id} value={r.id}>{r.title} ({formatDateTime(r.created_at)})</option>)}
          </select>
          {reports.length === 0 && <p className="mt-1 text-xs text-slate-600">No completed reports yet — generate one in the Report Builder first.</p>}
        </div>
        <fieldset>
          <legend className="label">Duration</legend>
          <div className="flex gap-4">
            {([60, 120, 180] as const).map((d) => (
              <label key={d} className="flex items-center gap-1 text-sm"><input type="radio" name="dur" className="accent-teal-700" checked={duration === d} disabled={d > maxDur} onChange={() => setDuration(d)} /> {d / 60} min</label>
            ))}
          </div>
        </fieldset>
        <fieldset>
          <legend className="label">Mode</legend>
          <div className="flex flex-wrap gap-4">
            <label className="flex items-center gap-1 text-sm"><input type="radio" name="mode" className="accent-teal-700" checked={mode === 'silent'} onChange={() => setMode('silent')} /> Silent (captions)</label>
            <label className="flex items-center gap-1 text-sm"><input type="radio" name="mode" className="accent-teal-700" checked={mode === 'narrated'} disabled={!ttsOk} onChange={() => setMode('narrated')} /> Narrated</label>
          </div>
          {!ttsOk && <p className="mt-1 text-xs text-amber-800">Narrated mode needs a text-to-speech provider, which is not available on this server{caps ? '' : ' (capabilities not loaded)'}.</p>}
          {mode === 'narrated' && ttsOk && (
            <div className="mt-2">
              <label className="label" htmlFor="v-voice">Voice</label>
              <select id="v-voice" className="input" value={voice} onChange={(e) => setVoice(e.target.value)}>
                <option value="">Default</option>
                {caps?.voices.map((v) => <option key={v} value={v}>{v}</option>)}
              </select>
            </div>
          )}
        </fieldset>
        <label className="flex items-center gap-2 text-sm"><input type="checkbox" className="h-4 w-4 accent-teal-700" checked={captions} onChange={(e) => setCaptions(e.target.checked)} /> Burn in captions</label>
        <fieldset className="md:col-span-2">
          <legend className="label">Sections</legend>
          <div className="flex flex-wrap gap-4">
            {SECTIONS.map((s) => (
              <label key={s.id} className="flex items-center gap-1 text-sm"><input type="checkbox" className="accent-teal-700" checked={sections.includes(s.id)} onChange={() => setSections(sections.includes(s.id) ? sections.filter((x) => x !== s.id) : [...sections, s.id])} /> {s.label}</label>
            ))}
          </div>
        </fieldset>
        <div className="md:col-span-2">
          <button type="submit" className="btn-primary" disabled={!reportId || sections.length === 0 || creating}><Film size={16} aria-hidden="true" /> {creating ? 'Creating…' : 'Create video job'}</button>
        </div>
      </form>

      <section className="card" aria-label="Video jobs">
        <h2 className="mb-2 font-semibold">Jobs</h2>
        {jobs.length === 0 ? <p className="text-sm text-slate-600">No video jobs yet.</p> : (
          <ul className="divide-y divide-slate-100">
            {jobs.map((j) => (
              <li key={j.id}>
                <button type="button" onClick={() => { setSelected(j.id); setVersion((v) => v + 1); }} aria-pressed={selected === j.id} className={`flex w-full flex-wrap items-center justify-between gap-2 px-2 py-2 text-left text-sm hover:bg-slate-50 ${selected === j.id ? 'bg-teal-50' : ''}`}>
                  <span className="font-mono text-xs">{j.id.slice(0, 8)}</span>
                  <span>{reports.find((r) => r.id === j.report_id)?.title ?? `report ${j.report_id.slice(0, 8)}`}</span>
                  <span className="text-xs text-slate-600">{formatDateTime(j.created_at)}</span>
                  <span className="rounded bg-slate-100 px-2 py-0.5 text-xs font-semibold">{label(j.state)}</span>
                </button>
              </li>
            ))}
          </ul>
        )}
      </section>

      {selected && (
        <>
          {pollError && !job && <Notice tone="error">{pollError}</Notice>}
          {!job && !pollError && <p className="text-sm text-slate-600">Loading job…</p>}
          {job && (
            <JobDetail
              key={job.id}
              job={job}
              onChange={(j) => {
                setData(j);
                setVersion((v) => v + 1);
              }}
            />
          )}
        </>
      )}
    </div>
  );
}

function JobDetail({ job, onChange }: { job: VideoJob; onChange: (j: VideoJob) => void }) {
  const [err, setErr] = useState<string | null>(null);
  const [busy, setBusy] = useState<string | null>(null);
  const [ack, setAck] = useState(false);
  const [drafts, setDrafts] = useState<Draft[]>([]);
  const [dirty, setDirty] = useState(false);
  const [videoUrl, setVideoUrl] = useState<string | null>(null);
  const [videoErr, setVideoErr] = useState<string | null>(null);

  const flags = job.validation?.flags ?? [];
  const editable = job.state === 'AWAITING_APPROVAL';

  useEffect(() => {
    if (!dirty) {
      setDrafts((job.storyboard?.scenes ?? []).map((s: Scene) => ({ id: s.id, title: s.title, on_screen_text: s.on_screen_text.join('\n'), narration: s.narration, duration_seconds: s.duration_seconds })));
    }
  }, [job.storyboard, job.updated_at, dirty]);

  useEffect(() => {
    if (job.state !== 'COMPLETED') return;
    let cancelled = false;
    let url: string | null = null;
    videoMp4Url(job.id).then((r) => {
      if (cancelled) return URL.revokeObjectURL(r.url);
      url = r.url;
      setVideoUrl(r.url);
    }).catch((e: unknown) => !cancelled && setVideoErr(e instanceof Error ? e.message : 'Could not load the video'));
    return () => {
      cancelled = true;
      if (url) URL.revokeObjectURL(url);
    };
  }, [job.id, job.state]);

  const act = async (name: string, fn: () => Promise<VideoJob>, after?: () => void) => {
    setBusy(name);
    setErr(null);
    try {
      const j = await fn();
      onChange(j);
      after?.();
    } catch (e) {
      setErr(e instanceof Error ? e.message : 'Action failed');
    } finally {
      setBusy(null);
    }
  };

  const total = useMemo(() => drafts.reduce((a, d) => a + (Number(d.duration_seconds) || 0), 0), [drafts]);
  const update = (i: number, patch: Partial<Draft>) => {
    setDirty(true);
    setDrafts((cur) => cur.map((d, k) => (k === i ? { ...d, ...patch } : d)));
  };

  const save = () =>
    act('save', () => {
      const sb = job.storyboard!;
      const scenes: Scene[] = sb.scenes.map((s, i) => ({
        ...s,
        on_screen_text: drafts[i].on_screen_text.split('\n').map((x) => x.trim()).filter(Boolean),
        narration: drafts[i].narration,
        duration_seconds: Number(drafts[i].duration_seconds) || s.duration_seconds,
      }));
      return saveStoryboard(job.id, { ...sb, scenes, total_duration_seconds: scenes.reduce((a, s) => a + s.duration_seconds, 0) });
    }, () => { setDirty(false); setAck(false); });

  const needsAck = flags.length > 0;
  const stateIdx = TIMELINE.indexOf(job.state);

  return (
    <section className="card space-y-5" aria-label="Video job detail">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <h2 className="font-semibold">Job <span className="font-mono text-sm">{job.id.slice(0, 8)}</span></h2>
        <span className="text-xs text-slate-600">Storyboard source: <b>{job.storyboard_source === 'claude' ? 'Claude via Mubit' : job.storyboard_source === 'template' ? 'Deterministic template' : 'not generated yet'}</b></span>
      </div>

      <ol className="flex flex-wrap gap-2" aria-label="Job state timeline">
        {TIMELINE.map((s, i) => {
          const current = s === job.state;
          const terminalBad = current && (s === 'FAILED' || s === 'CANCELLED');
          const passed = !terminalBad && i < stateIdx && stateIdx < 5;
          return (
            <li key={s} aria-current={current ? 'step' : undefined} className={`rounded px-2 py-1 text-xs font-semibold ${terminalBad ? 'bg-red-100 text-red-800' : current ? 'bg-teal-700 text-white' : passed ? 'bg-teal-100 text-teal-900' : 'bg-slate-100 text-slate-600'}`}>
              {label(s)}
            </li>
          );
        })}
      </ol>

      <div>
        <div className="flex justify-between text-xs text-slate-700"><span>{job.stage ? label(job.stage) : label(job.state)}</span><span>{Math.round(job.progress * 100)}%</span></div>
        <div className="mt-1 h-2 rounded bg-slate-200" role="progressbar" aria-label="Job progress" aria-valuemin={0} aria-valuemax={100} aria-valuenow={Math.round(job.progress * 100)}>
          <div className={`h-2 rounded ${job.state === 'FAILED' ? 'bg-red-600' : 'bg-teal-600'}`} style={{ width: `${Math.round(job.progress * 100)}%` }} />
        </div>
      </div>

      {job.error_message && <Notice tone="error">{job.error_message}</Notice>}
      {err && <Notice tone="error">{err}</Notice>}

      {flags.length > 0 && (
        <div className="rounded border border-amber-300 bg-amber-50 p-3 text-sm" role="region" aria-label="Validation flags">
          <p className="font-semibold text-amber-900">{flags.length} validation flag(s) — claims not backed by the report data</p>
          <ul className="mt-1 list-disc pl-5 text-amber-900">{flags.map((f, i) => <li key={i}><b>{f.scene_id}</b> · {f.type} ({f.severity}): {f.message}</li>)}</ul>
        </div>
      )}
      {job.validation?.ok && flags.length === 0 && <p className="text-xs text-teal-800">Storyboard validation passed with no flags.</p>}

      {job.storyboard && (
        <div className="space-y-3">
          <div>
            <h3 className="font-semibold">{job.storyboard.title}</h3>
            <p className="text-sm text-slate-700">{job.storyboard.executive_narrative}</p>
            <p className="mt-1 text-xs text-slate-600">Total duration: {editable ? total : job.storyboard.total_duration_seconds}s · {drafts.length} scenes</p>
          </div>
          <ul className="space-y-3">
            {job.storyboard.scenes.map((s, i) => {
              const sf = flags.filter((f) => f.scene_id === s.id);
              const d = drafts[i];
              if (!d) return null;
              return (
                <li key={s.id} className={`rounded border p-3 ${sf.length ? 'border-amber-400 bg-amber-50' : 'border-slate-200'}`}>
                  <div className="flex flex-wrap items-center justify-between gap-2">
                    <p className="text-sm font-semibold">{i + 1}. {s.title} <span className="text-xs font-normal text-slate-600">({s.type})</span></p>
                    {sf.length > 0 && <span className="rounded bg-amber-200 px-2 py-0.5 text-xs font-semibold text-amber-900">{sf.length} flag(s)</span>}
                  </div>
                  {sf.map((f, k) => <p key={k} className="mt-1 text-xs text-amber-900">⚠ {f.message}</p>)}
                  <div className="mt-2 grid gap-2 md:grid-cols-[1fr_1fr_6rem]">
                    <div>
                      <label className="label" htmlFor={`ost-${s.id}`}>On-screen text (one line per item)</label>
                      <textarea id={`ost-${s.id}`} className="input" rows={3} disabled={!editable} value={d.on_screen_text} onChange={(e) => update(i, { on_screen_text: e.target.value })} />
                    </div>
                    <div>
                      <label className="label" htmlFor={`nar-${s.id}`}>Narration</label>
                      <textarea id={`nar-${s.id}`} className="input" rows={3} disabled={!editable} value={d.narration} onChange={(e) => update(i, { narration: e.target.value })} />
                    </div>
                    <div>
                      <label className="label" htmlFor={`dur-${s.id}`}>Seconds</label>
                      <input id={`dur-${s.id}`} type="number" min={1} className="input" disabled={!editable} value={d.duration_seconds} onChange={(e) => update(i, { duration_seconds: Number(e.target.value) })} />
                    </div>
                  </div>
                  {(s.metric_refs.length > 0 || s.evidence_refs.length > 0) && <p className="mt-1 text-xs text-slate-600">Refs: {[...s.metric_refs, ...s.evidence_refs].join(', ')}</p>}
                </li>
              );
            })}
          </ul>
        </div>
      )}

      {editable && (
        <div className="space-y-3 border-t border-slate-200 pt-4">
          <div className="flex flex-wrap items-center gap-3">
            <button type="button" className="btn-secondary" disabled={!dirty || busy !== null} onClick={save}><Save size={16} aria-hidden="true" /> {busy === 'save' ? 'Saving…' : 'Save changes'}</button>
            {dirty && <span className="text-xs text-amber-800">Unsaved changes — save to re-validate before approving.</span>}
          </div>
          {needsAck && !job.approved && (
            <label className="flex items-start gap-2 text-sm"><input type="checkbox" className="mt-1 h-4 w-4 accent-teal-700" checked={ack} onChange={(e) => setAck(e.target.checked)} /> I have reviewed the validation flags and accept them.</label>
          )}
          <div className="flex flex-wrap gap-3">
            <button type="button" className="btn-primary" disabled={job.approved || dirty || busy !== null || (needsAck && !ack)} onClick={() => act('approve', () => approveVideo(job.id, ack))}><Check size={16} aria-hidden="true" /> {job.approved ? 'Approved' : busy === 'approve' ? 'Approving…' : 'Approve storyboard'}</button>
            <button type="button" className="btn-primary" disabled={!job.approved || dirty || busy !== null} title={job.approved ? undefined : 'Approve the storyboard first'} onClick={() => act('render', () => renderVideo(job.id))}><Play size={16} aria-hidden="true" /> {busy === 'render' ? 'Starting…' : 'Start render'}</button>
          </div>
        </div>
      )}

      {(job.state === 'QUEUED' || job.state === 'GENERATING_SCRIPT' || job.state === 'AWAITING_APPROVAL' || job.state === 'RENDERING') && (
        <button type="button" className="btn-danger" disabled={busy !== null} onClick={() => act('cancel', () => cancelVideo(job.id))}><XCircle size={16} aria-hidden="true" /> {busy === 'cancel' ? 'Cancelling…' : 'Cancel job'}</button>
      )}

      {job.state === 'COMPLETED' && (
        <div className="space-y-2">
          {videoErr && <Notice tone="error">Video could not be loaded: {videoErr}</Notice>}
          {!videoUrl && !videoErr && <p className="text-sm text-slate-600">Loading video…</p>}
          {videoUrl && (
            <>
              {/* captions are burned into the MP4 when enabled, so there is no separate text track */}
              <video src={videoUrl} controls className="w-full max-w-3xl rounded border border-slate-300 bg-black" aria-label="Rendered video preview" />
              <div>
                <button type="button" className="btn-primary" onClick={() => triggerDownload(videoUrl, `${slug(job.storyboard?.title ?? 'evalforge-video')}.mp4`)}><Download size={16} aria-hidden="true" /> Download MP4{job.artifact ? ` (${formatBytes(job.artifact.size_bytes)})` : ''}</button>
              </div>
            </>
          )}
        </div>
      )}
    </section>
  );
}

function VideosInner() {
  const params = useSearchParams();
  return <Video initialReport={params.get('report_id') ?? ''} />;
}

export default function VideosPage() {
  return (
    <ConnectGate>
      <Suspense fallback={<p className="text-sm text-slate-600">Loading…</p>}>
        <VideosInner />
      </Suspense>
    </ConnectGate>
  );
}
